const normalize = value => String(value || '').normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
const words = value => normalize(value).split(' ').filter(Boolean);
let searchBlockedUntil = 0;

export function durationSeconds(value) {
  const m = /^PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+(?:\.\d+)?)S)?$/.exec(value || '');
  return m ? Number(m[1] || 0) * 3600 + Number(m[2] || 0) * 60 + Number(m[3] || 0) : 0;
}
export function videoSearchQuery(track) {
  // Long contributor lists overconstrain YouTube search. Match credits and
  // duration after retrieval, keeping the search focused on the main artist.
  const artist = track.primaryArtist || track.artist.split(',')[0].trim();
  return `${track.title} ${artist} audio`.slice(0, 240);
}
export function chooseVideo(track, items) {
  const base = track.title.replace(/\([^)]*(?:feat\.?|featuring|with )[^)]*\)/gi, '');
  const title = words(base), artist = words(track.primaryArtist || track.artist.split(',')[0]);
  const expected = normalize(track.title), duration = track.durationMs / 1000;
  if (!title.length || !artist.length || !duration) return null;
  const ranked = [];
  for (const item of items) {
    if (!/^[\w-]{11}$/.test(item.id || '') || item.status?.embeddable !== true || item.status?.privacyStatus !== 'public') continue;
    if (item.contentDetails?.contentRating?.ytRating === 'ytAgeRestricted') continue;
    const region = item.contentDetails?.regionRestriction;
    if (region?.blocked?.includes('BR') || (region?.allowed && !region.allowed.includes('BR'))) continue;
    const actualDuration = durationSeconds(item.contentDetails?.duration);
    const delta = Math.abs(actualDuration - duration);
    if (!actualDuration || delta > Math.max(8, duration * .06)) continue;
    const videoTitle = normalize(item.snippet?.title), channel = normalize(item.snippet?.channelTitle);
    const hasVersion = (value, version) => ` ${value} `.includes(` ${version} `);
    if (['cover', 'karaoke', 'instrumental', 'slowed', 'sped up', 'nightcore', 'reaction', 'live', 'remix', 'acoustic', 'radio edit'].some(version => hasVersion(videoTitle, version) && !hasVersion(expected, version))) continue;
    if (['remix', 'live', 'radio edit', 'acoustic'].some(version => hasVersion(expected, version) && !hasVersion(videoTitle, version))) continue;
    const titleHit = title.filter(w => videoTitle.split(' ').includes(w)).length / title.length;
    const artistHit = artist.filter(w => `${videoTitle} ${channel}`.split(' ').includes(w)).length / artist.length;
    if (titleHit < .9 || artistHit < .65) continue;
    const description = String(item.snippet?.description || '');
    ranked.push({ id: item.id, score: titleHit * 4 + artistHit * 3 - delta / Math.max(duration, 1) + (/Provided to YouTube|Auto-generated by YouTube/i.test(description) ? 2 : 0) });
  }
  return ranked.sort((a, b) => b.score - a.score)[0]?.id || null;
}
async function youtubeGet(resource, params, key) {
  const url = new URL(`https://www.googleapis.com/youtube/v3/${resource}`);
  url.search = new URLSearchParams({ ...params, key });
  const response = await fetch(url, { signal: AbortSignal.timeout(6500) });
  if (!response.ok) {
    // A cold instance must not retry exhausted quota on every visitor request.
    searchBlockedUntil = Date.now() + 60000;
    throw new Error('youtube_unavailable');
  }
  return response.json();
}
export async function resolveVideo(track) {
  const verified = verifiedVideos[track.id];
  if (verified) return { videoId: verified, match: 'verified', provider: 'youtube' };
  const key = process.env.YOUTUBE_API_KEY;
  if (!key) return { videoId: null, reason: 'search_not_configured' };
  if (Date.now() < searchBlockedUntil) return { videoId: null, reason: 'search_unavailable' };
  try {
    return await cached(`youtube:${track.id}`, 86400000, async () => {
      const results = await youtubeGet('search', { part: 'snippet', type: 'video', q: videoSearchQuery(track), maxResults: '10', videoEmbeddable: 'true', videoSyndicated: 'true' }, key);
      const ids = (results.items || []).map(item => item.id?.videoId).filter(id => /^[\w-]{11}$/.test(id || ''));
      if (!ids.length) return { videoId: null, reason: 'no_match' };
      const details = await youtubeGet('videos', { part: 'snippet,contentDetails,status', id: ids.join(',') }, key);
      const videoId = chooseVideo(track, details.items || []);
      return videoId ? { videoId, provider: 'youtube', match: 'title_artist_duration' } : { videoId: null, reason: 'no_match' };
    });
  } catch { return { videoId: null, reason: 'search_unavailable' }; }
}
