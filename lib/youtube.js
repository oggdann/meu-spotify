// Verified label-distributed audio. No audio is extracted or hosted.
export const verifiedVideos = Object.freeze({
  '5PHOJumdwAHxdpPW2jofzO': 'lQUvn6nFqq0',
  '5OFlp1fOrfiSXOjw4wuSgy': 'PX0pgsOA_tA',
  '1S5lrLO2sr8Dz3HIWtPPIn': 'YIEjlOhzcbk',
  '4nvsRb9ypaqqDXcZxjn6ba': 'XSsRrlM3tNg',
  '4VbDJMkAX3dWNBdn3KH6Wx': 'FlBCUzGLce0'
});
const normalize = value => String(value || '').normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
const words = value => normalize(value).split(' ').filter(Boolean);
const hasPhrase = (value, phrase) => (' ' + value + ' ').includes(' ' + phrase + ' ');
const coverage = (expected, actual) => expected.length ? expected.filter(word => actual.has(word)).length / expected.length : 0;
const versionWords = /\b(?:ao vivo|en vivo|live|acustico|acoustic|remix|radio edit|remaster(?:ed)?(?: \d{4})?)\b/g;
let searchBlockedUntil = 0, searchBlockedReason = 'search_unavailable';

function titleVariants(title) {
  const full = String(title || '').replace(/\((?:feat\.?|ft\.?|featuring|with)\s[^)]*\)/gi, '');
  // Alternate song names are optional; part numbers and named mixes are not.
  const core = full.replace(/\(([^)]*)\)|\[([^\]]*)\]/g, (group, round, square) => {
    const detail = normalize(round || square);
    return /\b(?:part|pt|parte|vol|volume|version|versao|mix|remix|take|demo|edit)\b|^[ivx]+$/.test(detail) ? group : ' ';
  });
  const prefix = core.includes(':') ? core.split(':')[0] : core;
  const concise = words(prefix).length >= 3 ? prefix : core;
  return [...new Set([full, core, concise, concise.replace(/^mel[oô]\s+(?:de\s+)?/i, '')].map(value => normalize(value).replace(versionWords, ' ').replace(/\s+/g, ' ').trim()).filter(Boolean))];
}
function versions(value) {
  const text = normalize(value);
  return {
    live: ['live', 'ao vivo', 'en vivo'].some(version => hasPhrase(text, version)),
    acoustic: ['acoustic', 'acustico'].some(version => hasPhrase(text, version)),
    remix: hasPhrase(text, 'remix'),
    radio: hasPhrase(text, 'radio edit')
  };
}
function albumEvidence(track, text) {
  const album = normalize(track.album).replace(versionWords, ' ').replace(/\s+/g, ' ').trim();
  if (!album || titleVariants(track.title).includes(album)) return false;
  const terms = [...new Set(words(album).filter(word => !['a', 'o', 'as', 'os', 'de', 'do', 'da', 'em', 'no', 'na', 'the', 'of', 'in', 'at'].includes(word)))];
  return terms.length >= 2 && coverage(terms, new Set(words(text))) === 1;
}
export function durationSeconds(value) {
  const m = /^PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+(?:\.\d+)?)S)?$/.exec(value || '');
  return m ? Number(m[1] || 0) * 3600 + Number(m[2] || 0) * 60 + Number(m[3] || 0) : 0;
}
export function videoSearchQuery(track) {
  return videoSearchQueries(track)[0];
}
export function videoSearchQueries(track) {
  const artist = track.primaryArtist || String(track.artist || '').split(',')[0].trim();
  const variants = titleVariants(track.title);
  const core = variants.at(-1);
  if (!core || !artist) return [];
  // Do not require "audio": official videos and Topic uploads often omit it.
  // Broaden only after the previous query has no acceptable recording.
  return [...new Set([
    normalize(track.title + ' ' + artist),
    normalize(core + ' ' + artist),
    ...((track.artists || []).slice(1, 3).map(other => normalize(core + ' ' + other.name))),
    core
  ].map(query => query.slice(0, 240)))].slice(0, 5);
}
export function chooseVideo(track, items) {
  const titles = titleVariants(track.title).map(value => [...new Set(words(value))]);
  const artist = [...new Set(words(track.primaryArtist || String(track.artist || '').split(',')[0]))];
  const expected = normalize(track.title), expectedVersions = versions(track.title), duration = track.durationMs / 1000;
  if (!titles.length || !artist.length || !duration) return null;
  const ranked = [];
  for (const item of items) {
    if (!/^[\w-]{11}$/.test(item.id || '') || item.status?.embeddable !== true || item.status?.privacyStatus !== 'public') continue;
    if (item.contentDetails?.contentRating?.ytRating === 'ytAgeRestricted') continue;
    const region = item.contentDetails?.regionRestriction;
    if (region?.blocked?.includes('BR') || (region?.allowed && !region.allowed.includes('BR'))) continue;
    const actualDuration = durationSeconds(item.contentDetails?.duration);
    const delta = Math.abs(actualDuration - duration);
    if (!actualDuration || delta > Math.max(8, duration * .06)) continue;
    const videoTitle = normalize(item.snippet?.title), channel = normalize(item.snippet?.channelTitle);
    const description = String(item.snippet?.description || '');
    const distributedAudio = /Provided to YouTube|Auto-generated by YouTube/i.test(description);
    const artistOnChannel = coverage(artist, new Set(words(channel))) >= .9;
    const artistText = videoTitle + ' ' + channel + (distributedAudio ? ' ' + normalize(description) : '');
    const artistHit = coverage(artist, new Set(words(artistText)));
    const titleHit = Math.max(...titles.map(title => coverage(title, new Set(words(videoTitle)))));
    if (titleHit < .9 || artistHit < .65) continue;
    if (['cover', 'karaoke', 'instrumental', 'slowed', 'sped up', 'speed up', 'acelerado', 'nightcore', 'reaction'].some(version => hasPhrase(videoTitle, version) && !hasPhrase(expected, version))) continue;
    const actualVersions = versions(item.snippet?.title + (distributedAudio ? ' ' + description.split('\n').slice(0, 5).join(' ') : ''));
    const sameAlbum = (artistOnChannel || distributedAudio) && albumEvidence(track, videoTitle + ' ' + description);
    if (['remix', 'acoustic', 'radio'].some(version => expectedVersions[version] !== actualVersions[version])) continue;
    // Live recordings may name only their album/event on the artist's channel.
    // Require that release evidence when "Ao Vivo" itself is omitted.
    if (actualVersions.live !== expectedVersions.live && !(expectedVersions.live && !actualVersions.live && sameAlbum)) continue;
    const officialChannel = artistOnChannel && /\b(?:official|oficial|topic)\b/.test(channel);
    ranked.push({ id: item.id, score: titleHit * 4 + artistHit * 3 - delta / duration + (distributedAudio ? 2 : 0) + (officialChannel ? 2 : 0) + (sameAlbum ? 2 : 0) });
  }
  return ranked.sort((a, b) => b.score - a.score)[0]?.id || null;
}
async function youtubeGet(resource, params, key, signal) {
  const url = new URL('https://www.googleapis.com/youtube/v3/' + resource);
  url.search = new URLSearchParams({ ...params, key });
  let response;
  try { response = await fetch(url, { signal: AbortSignal.any([signal, AbortSignal.timeout(5000)]) }); }
  catch (error) {
    console.warn('youtube_lookup', JSON.stringify({ resource, failure: /timeout|abort/i.test(error.name || '') ? 'timeout' : 'network' }));
    throw error;
  }
  if (!response.ok) {
    let body; try { body = await response.json(); } catch {}
    const reasons = [...(body?.error?.errors || []).map(error => error.reason), body?.error?.status,
      ...(body?.error?.details || []).map(detail => detail.reason)].filter(reason => typeof reason === 'string');
    console.warn('youtube_lookup', JSON.stringify({ resource, status: response.status, reasons: reasons.filter(reason => /^[A-Za-z_]{1,80}$/.test(reason)).slice(0, 5) }));
    searchBlockedReason = reasons.some(reason => /quotaExceeded|dailyLimitExceeded/i.test(reason)) ? 'youtube_quota_exceeded'
      : response.status === 429 || reasons.some(reason => /rateLimitExceeded|RATE_LIMIT_EXCEEDED/.test(reason)) ? 'youtube_rate_limited'
      : reasons.some(reason => /keyInvalid|accessNotConfigured|ipRefererBlocked/i.test(reason)) ? 'search_not_configured' : 'search_unavailable';
    const wait = Math.max(searchBlockedReason === 'youtube_quota_exceeded' ? 3600000 : 60000, (Number(response.headers.get('Retry-After')) || 0) * 1000);
    searchBlockedUntil = Date.now() + wait;
    await writeShared('youtube:cooldown', { until: searchBlockedUntil, reason: searchBlockedReason }, wait / 1000);
    throw Object.assign(new Error(searchBlockedReason), { reason: searchBlockedReason });
  }
  return response.json();
}
export async function resolveVideo(track) {
  const verified = verifiedVideos[track.id];
  if (verified) return { videoId: verified, match: 'verified', provider: 'youtube' };
  const key = process.env.YOUTUBE_API_KEY;
  if (!key) return { videoId: null, reason: 'search_not_configured' };
  const saved = await readShared('youtube:match:v2:' + track.id);
  if (saved?.expires > Date.now()) return saved.result;
  const blocked = await readShared('youtube:cooldown');
  if (blocked?.until > Date.now()) return { videoId: null, reason: blocked.reason, retryAfter: Math.ceil((blocked.until - Date.now()) / 1000) };
  if (Date.now() < searchBlockedUntil) return { videoId: null, reason: searchBlockedReason, retryAfter: Math.ceil((searchBlockedUntil - Date.now()) / 1000) };
  try {
    const result = await cached('youtube:expanded:' + track.id, result => result.videoId ? 86400000 : 300000, async () => {
      const signal = AbortSignal.timeout(16000), seen = new Set();
      for (const q of videoSearchQueries(track)) {
        const results = await youtubeGet('search', { part: 'snippet', type: 'video', q, maxResults: '50', regionCode: 'BR', videoEmbeddable: 'true', videoSyndicated: 'true' }, key, signal);
        const ids = [...new Set((results.items || []).map(item => item.id?.videoId).filter(id => /^[\w-]{11}$/.test(id || '') && !seen.has(id)))];
        ids.forEach(id => seen.add(id));
        if (!ids.length) continue;
        const details = await youtubeGet('videos', { part: 'snippet,contentDetails,status', id: ids.join(',') }, key, signal);
        const videoId = chooseVideo(track, details.items || []);
        if (videoId) return { videoId, provider: 'youtube', match: 'title_artist_duration' };
      }
      return { videoId: null, reason: 'no_match' };
    });
    const ttl = result.videoId ? 7 * 86400 : 300;
    await writeShared('youtube:match:v2:' + track.id, { result, expires: Date.now() + ttl * 1000 }, ttl);
    return result;
  } catch (error) { return { videoId: null, reason: error.reason || 'search_unavailable', retryAfter: Math.max(60, Math.ceil((searchBlockedUntil - Date.now()) / 1000)) }; }
}
